// Regenerates supabase/034_leg_machines.sql from src/strength-catalog-legs.js so both stay identical.
// Run: node scripts/leg-machines-migration.mjs
import {writeFile} from 'node:fs/promises';
import {legMachineLifts} from '../src/strength-catalog-legs.js';
const catalog = JSON.stringify(legMachineLifts).replaceAll("'", "''");
await writeFile('supabase/034_leg_machines.sql', `-- More leg exercises in machines for the Strength Hub: lying leg curl, hip thrust, hip abduction and adduction,
-- glute kickback, standing and seated calf raise, calf raise in the leg press, single-leg leg press, belt squat and
-- Smith machine split squat.
-- Generated by scripts/leg-machines-migration.mjs from src/strength-catalog-legs.js; edit those, not the .sql.
-- Only new exercise ids are added. Saved workouts, XP, ranks and baselines are unchanged.
begin;
alter function public.arc_strength_meta(text) rename to arc_strength_meta_v33;
create function public.arc_strength_meta(id text) returns jsonb
language sql immutable set search_path=public,pg_temp as $$
 select coalesce((select value from jsonb_array_elements('${catalog}'::jsonb) where value->>'id'=id),public.arc_strength_meta_v33(id))
$$;
revoke all on function public.arc_strength_meta_v33(text) from public,anon,authenticated;
create or replace function public.training_expansion_ready() returns integer language sql stable as $$select 34$$;
insert into public.schema_migrations(name) values('034_leg_machines') on conflict do nothing;
notify pgrst,'reload schema';
commit;
`);
